"""Export the story, personalities, art and the Oracle's face for the web version.

Run from the repo root after editing anything in content/ or assets/oracle-face/:

    python tools/export_web.py

It writes web/data/content.js and web/data/face.js. The web page loads them as
plain scripts, so it also works when opened straight from disk. Needs PyYAML,
plus OpenCV and numpy for the face (pip install -e ".[camera]").
"""

from __future__ import annotations

import base64
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
FACE_DIR = ROOT / "assets" / "oracle-face"
OUT_DIR = ROOT / "web" / "data"
FACE_W, FACE_H = 128, 136  # keeps the painting's 744 x 787 shape

# Face colour classes, so the web page can pick palette accents per cell.
COLOR_CLASSES = {"none": 0, "orange": 1, "blue": 2, "red": 3, "green": 4, "white": 5}

HEADER = "// Generated by tools/export_web.py. Edit content/ or assets/ and re-run it; don't edit this file.\n"


def load_yaml(path: Path):
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def build_content() -> dict:
    config = load_yaml(ROOT / "config.yaml") or {}
    story_cfg = config.get("story", {})
    personalities = {}
    for path in sorted((ROOT / "content" / "personalities").glob("*.yaml")):
        data = load_yaml(path)
        personalities[data["id"]] = data
    art = {
        path.stem: path.read_text(encoding="utf-8")
        for path in sorted((ROOT / "content" / "art").glob("*.txt"))
    }
    return {
        "story": load_yaml(ROOT / "content" / "story.yaml"),
        "personalities": personalities,
        "art": art,
        "config": {
            "mishear_rate": story_cfg.get("mishear_rate", 0.25),
            "receipt_width": config.get("printer", {}).get("width", 32),
        },
    }


def _b64(array) -> str:
    return base64.b64encode(array.astype("uint8").tobytes()).decode("ascii")


def build_face() -> dict:
    try:
        import cv2
        import numpy as np
    except ImportError:
        raise SystemExit('The face export needs OpenCV: pip install -e ".[camera]"')

    def gray(name: str):
        image = cv2.imread(str(FACE_DIR / name), cv2.IMREAD_GRAYSCALE)
        if image is None:
            raise SystemExit(f"missing {FACE_DIR / name}")
        return cv2.resize(image, (FACE_W, FACE_H), interpolation=cv2.INTER_AREA)

    color = cv2.imread(str(FACE_DIR / "color.jpg"))
    if color is None:
        raise SystemExit(f"missing {FACE_DIR / 'color.jpg'}")
    color = cv2.resize(color, (FACE_W, FACE_H), interpolation=cv2.INTER_AREA)
    mask = gray("mask.png")

    hsv = cv2.cvtColor(color, cv2.COLOR_BGR2HSV)
    hue = hsv[..., 0].astype(int)  # 0..179
    sat = hsv[..., 1].astype(int)
    val = hsv[..., 2].astype(int)
    classes = np.zeros((FACE_H, FACE_W), np.uint8)
    classes[(hue >= 10) & (hue < 35)] = COLOR_CLASSES["orange"]
    classes[(hue >= 35) & (hue < 85)] = COLOR_CLASSES["green"]
    classes[(hue >= 85) & (hue < 140)] = COLOR_CLASSES["blue"]
    classes[(hue < 10) | (hue >= 160)] = COLOR_CLASSES["red"]
    classes[(sat < 50) & (val > 170)] = COLOR_CLASSES["white"]
    classes[mask < 128] = COLOR_CLASSES["none"]

    return {
        "w": FACE_W,
        "h": FACE_H,
        "classes": COLOR_CLASSES,
        "height": _b64(gray("height.png")),
        "sculpt": _b64(gray("sculpt.png")),
        "mask": _b64(mask),
        "luma": _b64(cv2.cvtColor(color, cv2.COLOR_BGR2GRAY)),
        "color": _b64(classes),
    }


def write_js(path: Path, name: str, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(data, ensure_ascii=False, indent=1 if name == "ORACLE_CONTENT" else None)
    path.write_text(f"{HEADER}window.{name} = {body};\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    write_js(OUT_DIR / "content.js", "ORACLE_CONTENT", build_content())
    if "--content-only" not in args:
        write_js(OUT_DIR / "face.js", "ORACLE_FACE", build_face())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
